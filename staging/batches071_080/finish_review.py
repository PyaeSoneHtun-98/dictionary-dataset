sources = {}
entries = []
for name in ['agent_a', 'agent_b', 'agent_c', 'coordinator']:
    for entry in read(ROOT/name/'selected_entries.json'):
        entry = copy.deepcopy(entry)
        word = entry['word']
        assert word not in sources, word
        sources[word] = name
        if word in overrides['meaningCorrections']:
            entry['meanings'][0]['burmese'] = overrides['meaningCorrections'][word]
        if word in overrides['ipaCorrections']:
            entry['pronunciation'] = overrides['ipaCorrections'][word]
        if word in overrides['posCorrections']:
            entry['meanings'][0]['partOfSpeech'] = overrides['posCorrections'][word]
        if word in {'pointy','saggy','bendy','croaky','snarly'}:
            stem = word[:-1]
            entry['forms'].extend([stem+'ier', stem+'iest'])
        entries.append(entry)

def rank(entry):
    w = entry['word']
    return (-max(zipf_frequency(w,'en'), 2.0 if w in promoted else 0), w)

eligible = sorted([e for e in entries if e['word'] not in deferred and e['word'] not in overrides['rejections']], key=rank)
count = (len(eligible)//500)*500
# Publish complete batches, retaining a candidate surplus for later review.
selected = eligible[:count]
selected_heads = {e['word'] for e in selected}
old = set(zlib.decompress(base64.b64decode((REPO/'lookup/used_keys_current.zlib.b64').read_text().strip())).decode().splitlines())
for number in range(61,71):
    for previous in read(REPO/'DictionaryExtensionBatches'/f'dictionary_batch_{number:03d}.json')['entries']:
        old.add(previous['word'])
        old.update(previous['forms'])
assert len(old) == 54600, 'The baseline through Batch 070 changed.'
owners = {w: 'prior' for w in old}
owners.update({w: w for w in selected_heads})
excluded_forms = []
for e in selected:
    kept = []
    for form in e['forms']:
        if form in owners:
            excluded_forms.append({'word': e['word'], 'form': form, 'owner': owners[form]})
        else:
            kept.append(form)
            owners[form] = e['word']
    e['forms'] = kept

write(ROOT/'selected_entries.json', selected)
write(ROOT/'reserves.json', [{'entry':e, 'source':sources[e['word']], 'reason':overrides['rejections'].get(e['word'], 'Deferred after subtitle-usefulness review' if e['word'] in deferred else 'Candidate surplus below this run\'s publication priority')} for e in entries if e['word'] not in selected_heads])
write(ROOT/'selection_review.json', {'reviewDate':'2026-10-07', 'inputEntries':len(entries), 'eligibleAfterReview':len(eligible), 'publishedEntries':len(selected), 'sourceByHeadword':{e['word']:sources[e['word']] for e in selected}, 'deferredWords':sorted(deferred & sources.keys()), 'promotedWords':sorted(promoted & selected_heads), 'excludedForms':excluded_forms, 'selectionMethod':'Manual subtitle-usefulness review, then wordfreq 3.1.1 English Zipf tie-breaker with explicit dialogue priorities; only complete 500-entry batches.'})
print(json.dumps({'drafts':len(entries),'eligible':len(eligible),'selected':len(selected),'reserves':len(entries)-len(selected),'forms':sum(len(e['forms']) for e in selected),'formCollisionsRemoved':excluded_forms},indent=2))
