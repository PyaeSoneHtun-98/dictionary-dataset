from wordfreq import zipf_frequency

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[1]

def read(path):
    return json.loads(path.read_text(encoding='utf-8'))

def write(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')

overrides = read(ROOT/'root_review_overrides.json')
overrides['rejections']['cowry'] = 'Spelling variant of cowrie in the combined drafts; retain one canonical entry instead of padding with both.'
overrides['ipaCorrections'].update({'semiofficial':'/ˌsɛmiəˈfɪʃəl/', 'preterm':'/ˈpriˌtɝm/', 'entrepreneurialism':'/ˌɑntrəprəˈnɝiəˌlɪzəm/', 'whew':'/hju/'})
overrides['meaningCorrections'].update({
    'wildcard': ['မည်သို့ဖြစ်မည်ကို ခန့်မှန်းမရသောလူ သို့မဟုတ် အရာ', 'အခြားစာလုံးများကို ကိုယ်စားပြုသည့် သင်္ကေတ'],
    'motorsport': ['မော်တော်ယာဉ် အပြိုင်မောင်းနှင်သည့်အားကစား'],
    'partway': ['လမ်းတစ်ပိုင်းအထိ', 'တစ်စိတ်တစ်ပိုင်းအထိ'],
    'noncommissioned': ['အရာခံနှင့် အကြပ်အဆင့် စစ်မှုထမ်းဖြစ်သော'],
    'smirch': ['နာမည်ပျက်အောင် လုပ်သည်', 'စွန်းထင်းစေသည်'],
    'bulgur': ['ပြုတ်ခြောက်ပြီး အစိတ်ငယ်များခွဲထားသည့် ဂျုံ'],
    'frappe': ['ရေခဲနှင့် မွှေထားသော အချိုဖျော်ရည်'],
    'millipede': ['ခြေထောက်များစွာရှိပြီး နှေးကွေးစွာတွားသွားသည့် ကင်းခြေများမျိုး'],
    'beriberi': ['ဗီတာမင်ဘီတစ် ချို့တဲ့၍ဖြစ်သော ထုံနာရောဂါ'],
    'shiftily': ['မရိုးမသား ကောက်ကျစ်သည့်ဟန်ဖြင့်'],
    'rapaciously': ['လုယက်ရယူလိုစိတ် ပြင်းပြစွာ'],
    'cheesiness': ['ပေါပေါပဲပဲ ဟန်လုပ်ထား၍ အရသာမရှိမှု'],
})
overrides['posCorrections'] = {'antiterrorism': 'noun'}
overrides['meaningCorrections']['antiterrorism'] = ['အကြမ်းဖက်မှုကို တားဆီးတိုက်ဖျက်ရေး']
write(ROOT/'final_review_overrides.json', overrides)

